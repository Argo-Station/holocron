// build.mjs — esbuild precompile for the Holocron apps (BABEL_PRECOMPILE_RECON §8, Option B).
//
// Replaces the in-browser @babel/standalone compile with an ahead-of-time build:
//   /vendor.js                       React+ReactDOM (prod, off-CDN) + shared diceUI + diceRoll — §8b chunk
//   player/app.js · gm/app.js        each app's inline block, JSX precompiled (classic transform)
//   lib/dice/diceSurface.js          shared cinematic dice surface (dice + gm)
//   lib/game/hyperspaceRun/ui.js     hyperspace-run overlay (gm)
//   (dice's inline bootstrap is plain JS — no JSX — so dice needs no app.js)
//   dist/lib/**.js                   B-1912: a minified copy of every hand-written lib/ .js; the pages load these
//
// Apps + the JSX includes use esbuild TRANSFORM (not bundle): they stay classic <script> files
// with the same global scope they have today (React/ReactDOM/SWRPGDice/data-layer globals on
// window), so this is purely compile-ahead — Lap 0/1 proved this path mounts clean. Only React is
// bundled (a real npm module). Source maps ship for every transform so devtools debugs JSX.
// vendor.js loads after each app's diceEngine.js (SWRPGDice) and before the app block; no app lib
// executes React at load (verified Lap 2), so React arriving via vendor.js precedes every render.
//
// Usage:  npm run build        (one-shot)
//         npm run watch        (rebuild on save — keeps the serve.py edit/refresh loop)
import esbuild from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, rmSync, watch as fsWatch } from 'node:fs';
import { dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
// B-423: the build's source lists live in ONE module so the TREE STAMP below is computed from the
// same document the build compiles — never a hand-typed second list. See build/sources.mjs.
import { TRANSFORMS, VENDOR_INPUTS, RAW_LIB_OUT, rawLibFiles, treeStamp } from './build/sources.mjs';
// B-139 (ruling release-r7-bug-burndown ADDENDUM 426 §2): player/app.jsx is cut into first paint + two chunks.
import { cut as cutPlayer, textFor as playerText, lazyCheck as playerLazyCheck, CHUNK_OUT as PLAYER_OUT } from './build/playerSplit.mjs';

const watch = process.argv.includes('--watch');
// F-48 G13: a build stamp. CF Pages sets CF_PAGES_COMMIT_SHA per deploy (stable, unique); locally
// fall back to a timestamp so `npm run watch` produces a fresh id each rebuild. Stamped into every
// bundle via `define` (__HOLOCRON_BUILD__) AND written to /version.json — the beacon compares them.
const BUILD_ID = process.env.CF_PAGES_COMMIT_SHA || ('dev-' + Date.now());
// The release version (ruling release-r2-proof ADDENDUM 6 Q1): package.json is the one source. It names
// the release; BUILD_ID/head name the exact deploy, and the beacon keeps comparing `build`, never this.
const VERSION = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8')).version;
const DEFINE = { __HOLOCRON_BUILD__: JSON.stringify(BUILD_ID), __HOLOCRON_VERSION__: JSON.stringify(VERSION) };
const COMMON = { target: 'es2018', minify: true, logLevel: 'info', define: DEFINE };
const JSX = { jsx: 'transform', jsxFactory: 'React.createElement', jsxFragment: 'React.Fragment' };

// TRANSFORMS (what compiles) and VENDOR_INPUTS (the concatenated chunk's inputs) are imported
// from build/sources.mjs — one list, read by the build and by B-423's tree stamp.

// vendor.js = [React/ReactDOM IIFE bundle] + [diceUI classic transform], concatenated so
// window.React is set before diceUI's code runs. diceUI also needs window.SWRPGDice, which each
// page's lib/shared/diceEngine.js <script> defines before /vendor.js loads.
async function buildVendor() {
  const react = await esbuild.build({
    entryPoints: ['build/vendor.entry.js'], bundle: true, write: false, format: 'iife',
    ...COMMON, define: { 'process.env.NODE_ENV': '"production"', ...DEFINE },
  });
  const ui = await esbuild.build({
    entryPoints: ['lib/shared/ui.jsx'], bundle: false, write: false, ...JSX, ...COMMON,
  });
  const dice = await esbuild.build({
    entryPoints: ['lib/shared/diceUI.jsx'], bundle: false, write: false, ...JSX, ...COMMON,
  });
  const diceRoll = await esbuild.build({
    entryPoints: ['lib/shared/diceRoll.jsx'], bundle: false, write: false, ...JSX, ...COMMON,
  });
  // Order: React first (defines window.React) → ui + dice + diceRoll IIFEs read it off the global.
  // diceRoll after diceUI (both publish onto window.SWRPGDice; order is render-time irrelevant, kept tidy).
  writeFileSync('vendor.js',
    '/* GENERATED by build.mjs — do not edit; gitignored. Source: build/vendor.entry.js + lib/shared/ui.jsx + lib/shared/diceUI.jsx + lib/shared/diceRoll.jsx */\n'
    + react.outputFiles[0].text + '\n' + ui.outputFiles[0].text + '\n' + dice.outputFiles[0].text + '\n' + diceRoll.outputFiles[0].text);
  console.log('  wrote vendor.js (React+ReactDOM prod + SWRPGUI + diceUI + diceRoll)');
}

// B-1912 (ADDENDUM 761 item 2.1): each raw lib/ .js → dist/lib/<same path>.js, esbuild transform with minify and es2018
// ONLY. No define: a copy never carries the build stamp, so the served copy is byte-identical to the local one and
// needs no normalising (PRAXIS §4). No source map in this lap. `/*! */` and `@license` comments stay (esbuild's default).
// The directory is rebuilt whole, so a deleted source never leaves a copy behind.
const RAW_MIN = { loader: 'js', minify: true, target: 'es2018' };
async function buildRawLibOne(f) {
  const out = RAW_LIB_OUT + f;
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, (await esbuild.transform(readFileSync(f, 'utf8'), { ...RAW_MIN, sourcefile: f })).code);
}
async function buildRawLib() {
  rmSync(RAW_LIB_OUT + 'lib', { recursive: true, force: true });
  const files = rawLibFiles(process.cwd());
  for (const f of files) await buildRawLibOne(f);
  console.log(`  wrote ${files.length} raw lib copies to ${RAW_LIB_OUT}lib/`);
}

const opts = (t) => ({ entryPoints: [t.in], outfile: t.out, bundle: false, sourcemap: true, ...JSX, ...COMMON });

// B-139: the player's three classic scripts from ONE source. Each is app.jsx with the other outputs' pieces
// blanked line-for-line, so every source map points at real app.jsx lines. A refusal (a first-paint piece naming
// a chunk symbol outside a gate site, a root out of its chunk, a dynamic lookup) EXITS the build non-zero.
async function buildPlayer(t) {
  const src = readFileSync(t.in, 'utf8');
  const { P, where, refusals: cutRefusals } = cutPlayer(src);
  // split A's check (ADDENDUM 426 §1): a lazy file loaded by the page, or read by an unpinned reader, refuses too
  const refusals = cutRefusals.concat(playerLazyCheck(src, P, (f) => readFileSync(f, 'utf8'))
    .map((why) => ({ line: '-', from: 'split A', name: why, chunk: 'lazy', ctx: '' })));
  if (refusals.length) {
    console.error(`\n  ✗ B-139 player split REFUSED — ${refusals.length} reference(s) the cut cannot honour:`);
    for (const r of refusals) console.error(`    ${t.in}:${r.line} ${r.from} → ${r.name} [${r.chunk}]  …${r.ctx}…`);
    throw new Error('player split refused (build/playerSplit.mjs)');
  }
  for (const [part, out] of Object.entries(PLAYER_OUT)) {
    await esbuild.build({
      stdin: { contents: playerText(src, P, where, part), sourcefile: t.in, loader: 'jsx', resolveDir: process.cwd() },
      outfile: out, bundle: false, sourcemap: true, ...JSX, ...COMMON,
    });
  }
}

async function run() {
  // G13 beacon: the tiny version file the app polls. max-age=0 in _headers, so a returning visitor
  // always sees the CURRENT deploy's id and the app can offer a one-tap reload when its own stamp lags.
  // B-423 (`b412-species-parity-gate` A1, R-B412G-A1-3): the beacon file also carries this TREE's
  // IDENTITY, so a smoke can ask the PORT what it is serving instead of trusting local mtimes.
  // `build` stays first and unchanged — the update beacon and `deploy_check` read that field only.
  const stamp = treeStamp(process.cwd());
  let head = process.env.CF_PAGES_COMMIT_SHA || '';
  try { head = head || execFileSync('git', ['rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim(); }
  catch (e) { head = head || 'unknown'; }   // a tarball checkout has no git; the stamp still works
  writeFileSync('version.json', JSON.stringify({
    build: BUILD_ID, head: head, src: stamp.src, files: stamp.files, version: VERSION,
  }) + '\n');
  console.log('  wrote version.json (version ' + VERSION + ' · build ' + BUILD_ID + ' · head ' + head
              + ' · src ' + stamp.src.slice(0, 12) + ' over ' + stamp.files + ' files)');
  await buildVendor();
  await buildRawLib();
  if (watch) {
    for (const t of TRANSFORMS) {
      if (t.split) {   // B-139: the split is a custom multi-build, watched by hand like the vendor chunk
        await buildPlayer(t);
        let pt = null;
        fsWatch(t.in, () => { clearTimeout(pt); pt = setTimeout(() => buildPlayer(t)
          .then(() => console.log('  player split rebuilt')).catch((e) => console.error(e)), 120); });
        continue;
      }
      const ctx = await esbuild.context(opts(t)); await ctx.watch();
    }
    // T3a: also watch the VENDOR inputs — esbuild's per-transform watch above doesn't cover the
    // concatenated vendor.js (buildVendor is a custom multi-build + writeFileSync), so a shared-dice
    // edit shipped stale silently (the Lane-B trap). fs.watch → debounced buildVendor().
    let timer = null;
    for (const f of VENDOR_INPUTS) {
      fsWatch(f, () => {
        clearTimeout(timer);
        timer = setTimeout(() => buildVendor()
          .then(() => console.log('  vendor.js rebuilt (vendor input changed)'))
          .catch((e) => console.error(e)), 120);
      });
    }
    // B-1912: a saved raw lib/ .js re-writes its dist/ copy (the page loads the copy, so an unwatched copy ships stale)
    const rawOut = new Set(TRANSFORMS.map((t) => t.out));
    fsWatch('lib', { recursive: true }, (ev, name) => {
      const f = name && ('lib/' + String(name).split('\\').join('/'));
      if (!f || !f.endsWith('.js') || rawOut.has(f)) return;
      buildRawLibOne(f).then(() => console.log('  ' + RAW_LIB_OUT + f + ' rebuilt')).catch(() => buildRawLib().catch((e) => console.error(e)));
    });
    console.log(`  watching ${TRANSFORMS.length} transforms + ${VENDOR_INPUTS.length} vendor inputs + raw lib/ …`);
  } else {
    for (const t of TRANSFORMS) await (t.split ? buildPlayer(t) : esbuild.build(opts(t)));
    console.log(`  wrote ${TRANSFORMS.length} transforms (+ .map)`);
  }
}

run().catch((e) => { console.error(e); process.exit(1); });
